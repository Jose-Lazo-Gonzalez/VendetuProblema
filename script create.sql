-- VendeTuProblema · schema PostgreSQL (Neon)
-- Reinicia el esquema para poder relanzar el script las veces que haga falta.
DROP SCHEMA IF EXISTS public CASCADE;
CREATE SCHEMA public;

-- ===== TIPOS ENUM =====
CREATE TYPE tipo_cliente AS ENUM ('particular', 'empresa');
CREATE TYPE nivel_admin AS ENUM ('moderador', 'superadmin');
CREATE TYPE estado_problema AS ENUM ('abierto', 'cerrado', 'cancelado');
CREATE TYPE estado_oferta AS ENUM ('pendiente', 'aceptada', 'rechazada');
CREATE TYPE estado_contratacion AS ENUM (
  'pendiente_pago', 'en_curso', 'pendiente_conformidad',
  'terminada', 'con_incidencia', 'cancelada'
);
CREATE TYPE estado_pago AS ENUM ('pendiente', 'retenido', 'liberado', 'reembolsado', 'fallido');
CREATE TYPE tipo_movimiento AS ENUM ('recarga', 'retirada', 'pago_enviado', 'cobro_recibido', 'reembolso');
CREATE TYPE estado_movimiento AS ENUM ('pendiente', 'completado', 'fallido');

-- ===== USUARIOS (jerarquía: cliente, profesional, administrador) =====
CREATE TABLE usuario (
  id INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  nombre VARCHAR(100) NOT NULL,
  email VARCHAR(150) NOT NULL UNIQUE,
  password_hash VARCHAR(255) NOT NULL,
  telefono VARCHAR(20),
  fecha_registro TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
  fecha_aceptacion_politica TIMESTAMP NOT NULL,
  activo BOOLEAN NOT NULL DEFAULT TRUE,
  fecha_baja TIMESTAMP
);

CREATE TABLE cliente (
  id_usuario INT PRIMARY KEY REFERENCES usuario(id) ON DELETE CASCADE,
  tipo tipo_cliente NOT NULL DEFAULT 'particular',
  nif VARCHAR(20)
);

CREATE TABLE profesional (
  id_usuario INT PRIMARY KEY REFERENCES usuario(id) ON DELETE CASCADE,
  descripcion TEXT,
  experiencia TEXT
);

CREATE TABLE administrador (
  id_usuario INT PRIMARY KEY REFERENCES usuario(id) ON DELETE CASCADE,
  nivel nivel_admin NOT NULL DEFAULT 'moderador'
);

-- ===== CATÁLOGO =====
CREATE TABLE categoria (
  id INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  nombre VARCHAR(80) NOT NULL UNIQUE
);

CREATE TABLE profesional_categoria (
  id_profesional INT NOT NULL REFERENCES profesional(id_usuario) ON DELETE CASCADE,
  id_categoria INT NOT NULL REFERENCES categoria(id) ON DELETE RESTRICT,
  PRIMARY KEY (id_profesional, id_categoria)
);

-- ===== FLUJO PRINCIPAL =====
CREATE TABLE problema (
  id INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  id_cliente INT NOT NULL REFERENCES cliente(id_usuario) ON DELETE RESTRICT,
  id_categoria INT NOT NULL REFERENCES categoria(id) ON DELETE RESTRICT,
  titulo VARCHAR(150) NOT NULL,
  descripcion TEXT NOT NULL,
  estado estado_problema NOT NULL DEFAULT 'abierto',
  prioritario BOOLEAN NOT NULL DEFAULT FALSE,
  fecha_publicacion TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE TABLE oferta (
  id INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  id_problema INT NOT NULL REFERENCES problema(id) ON DELETE CASCADE,
  id_profesional INT NOT NULL REFERENCES profesional(id_usuario) ON DELETE RESTRICT,
  precio DECIMAL(10,2) NOT NULL CHECK (precio > 0),
  descripcion TEXT NOT NULL,
  estado estado_oferta NOT NULL DEFAULT 'pendiente',
  fecha TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
  UNIQUE (id_problema, id_profesional),
  UNIQUE (id, id_problema)  -- necesario para la FK compuesta de contratacion
);

CREATE TABLE contratacion (
  id INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  id_oferta INT NOT NULL UNIQUE,
  id_problema INT NOT NULL UNIQUE REFERENCES problema(id) ON DELETE RESTRICT,
  precio_acordado DECIMAL(10,2) NOT NULL CHECK (precio_acordado > 0),
  estado estado_contratacion NOT NULL DEFAULT 'pendiente_pago',
  fecha_inicio TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
  fecha_fin TIMESTAMP,
  -- la oferta elegida tiene que ser de ESE problema
  FOREIGN KEY (id_oferta, id_problema) REFERENCES oferta(id, id_problema) ON DELETE RESTRICT
);

CREATE TABLE pago (
  id INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  id_contratacion INT NOT NULL REFERENCES contratacion(id) ON DELETE RESTRICT,
  importe DECIMAL(10,2) NOT NULL CHECK (importe > 0),
  estado estado_pago NOT NULL DEFAULT 'pendiente',
  referencia_proveedor VARCHAR(100),
  fecha TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE TABLE evidencia (
  id INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  id_contratacion INT NOT NULL REFERENCES contratacion(id) ON DELETE CASCADE,
  descripcion VARCHAR(255),
  ruta_archivo VARCHAR(255) NOT NULL,
  fecha TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP
);

-- ===== MONEDERO =====
CREATE TABLE monedero (
  id INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  id_usuario INT NOT NULL UNIQUE REFERENCES usuario(id) ON DELETE RESTRICT,
  saldo DECIMAL(10,2) NOT NULL DEFAULT 0 CHECK (saldo >= 0)
);

CREATE TABLE movimiento_monedero (
  id INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  id_monedero INT NOT NULL REFERENCES monedero(id) ON DELETE RESTRICT,
  id_pago INT REFERENCES pago(id) ON DELETE RESTRICT,  -- NULL en recargas y retiradas
  tipo tipo_movimiento NOT NULL,
  importe DECIMAL(10,2) NOT NULL CHECK (importe > 0),
  estado estado_movimiento NOT NULL DEFAULT 'pendiente',
  referencia_externa VARCHAR(100),
  fecha TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP
);

-- ===== COMUNICACIÓN Y CONFIANZA =====
CREATE TABLE conversacion (
  id INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  id_problema INT NOT NULL REFERENCES problema(id) ON DELETE CASCADE,
  id_profesional INT NOT NULL REFERENCES profesional(id_usuario) ON DELETE RESTRICT,
  fecha_creacion TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
  UNIQUE (id_problema, id_profesional)
);

CREATE TABLE mensaje (
  id INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  id_conversacion INT NOT NULL REFERENCES conversacion(id) ON DELETE CASCADE,
  id_remitente INT NOT NULL REFERENCES usuario(id) ON DELETE RESTRICT,
  contenido TEXT NOT NULL,
  fecha_envio TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE TABLE valoracion (
  id INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  id_contratacion INT NOT NULL REFERENCES contratacion(id) ON DELETE RESTRICT,
  id_autor INT NOT NULL REFERENCES usuario(id) ON DELETE RESTRICT,
  id_destinatario INT NOT NULL REFERENCES usuario(id) ON DELETE RESTRICT,
  puntuacion SMALLINT NOT NULL CHECK (puntuacion BETWEEN 1 AND 5),
  comentario TEXT,
  fecha TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
  UNIQUE (id_contratacion, id_autor)
);

CREATE TABLE notificacion (
  id INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  id_usuario INT NOT NULL REFERENCES usuario(id) ON DELETE CASCADE,
  tipo VARCHAR(50) NOT NULL,
  texto VARCHAR(255) NOT NULL,
  leida BOOLEAN NOT NULL DEFAULT FALSE,
  fecha TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP
);